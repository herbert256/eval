"""Generate independent document-import fixtures (python-docx, reportlab, openpyxl, python-pptx)."""
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from html import escape
from docx import Document
from docx.shared import Inches
from reportlab.pdfgen import canvas
from reportlab.lib.pdfencrypt import StandardEncryption
from openpyxl import Workbook
from pptx import Presentation
from pptx.util import Inches as SlideInches

root = Path(__file__).resolve().parents[1]
out = root / "app/src/androidTest/assets/documents"
out.mkdir(parents=True, exist_ok=True)
board = root / "app/src/androidTest/assets/url-scan/lichess-italian-black.png"
fen = "4k3/8/8/8/8/8/8/4K3 b - - 0 1"
pgn = '[Event "Document game"]\n[White "Alice"]\n[Black "Bob"]\n\n1. e4 e5 2. Nf3 *'

doc = Document()
doc.add_heading("Chess document import fixture", 0)
p = doc.add_paragraph()
p.add_run(fen[:13]).bold = True
p.add_run(fen[13:])
for line in pgn.splitlines():
    doc.add_paragraph(line)
doc.add_picture(str(board), width=Inches(5))
doc.save(out / "chess.docx")

pdf = canvas.Canvas(str(out / "chess.pdf"), pagesize=(612, 792))
pdf.setFont("Helvetica", 11)
for i, line in enumerate([fen, "", *pgn.splitlines()]):
    pdf.drawString(35, 745 - i * 20, line)
pdf.showPage()
pdf.setPageSize((612, 420))
pdf.drawImage(str(board), 18, 30, width=576, height=360)
pdf.save()

pdf = canvas.Canvas(str(out / "locked.pdf"), encrypt=StandardEncryption("fixture-password", strength=128))
pdf.drawString(30, 700, fen)
pdf.save()

workbook = Workbook()
workbook.active["A1"] = fen
workbook.active["A2"] = pgn
workbook.save(out / "chess.xlsx")

slides = Presentation()
slide = slides.slides.add_slide(slides.slide_layouts[6])
box = slide.shapes.add_textbox(SlideInches(.5), SlideInches(.5), SlideInches(8), SlideInches(5))
box.text = fen + "\n" + pgn
slides.save(out / "chess.pptx")

with ZipFile(out / "chess.odt", "w", ZIP_DEFLATED) as archive:
    archive.writestr("mimetype", "application/vnd.oasis.opendocument.text")
    paragraphs = "".join(f"<text:p>{escape(line)}</text:p>" for line in [fen, *pgn.splitlines()])
    archive.writestr("content.xml", '<office:document-content xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" xmlns:text="urn:oasis:names:tc:opendocument:xmlns:text:1.0"><office:body><office:text>' + paragraphs + '</office:text></office:body></office:document-content>')
with ZipFile(out / "chess.epub", "w", ZIP_DEFLATED) as archive:
    archive.writestr("mimetype", "application/epub+zip")
    archive.writestr("META-INF/container.xml", '<container xmlns="urn:oasis:names:tc:opendocument:xmlns:container" version="1.0"><rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles></container>')
    archive.writestr("OEBPS/content.opf", '<package xmlns="http://www.idpf.org/2007/opf" version="3.0" unique-identifier="book"><metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:identifier id="book">fixture</dc:identifier><dc:title>Chess fixture</dc:title><dc:language>en</dc:language></metadata><manifest><item id="page" href="page.xhtml" media-type="application/xhtml+xml"/></manifest><spine><itemref idref="page"/></spine></package>')
    archive.writestr("OEBPS/page.xhtml", f'<html xmlns="http://www.w3.org/1999/xhtml"><body><p>{fen}</p><pre>{escape(pgn)}</pre></body></html>')
with ZipFile(out / "chess.zip", "w", ZIP_DEFLATED) as archive:
    archive.writestr("position.fen", fen)
    archive.writestr("game.pgn", pgn)

rtf = r"{\rtf1\ansi\uc1{\fonttbl{\f0 Fixture Font;}}" + fen[:13] + r"\b " + fen[13:] + r"\b0\par "
rtf += pgn.replace("\n", r"\par ") + r"\par R\u233?sum\u233?"
rtf += r"{\pict\pngblip " + board.read_bytes().hex() + "}}"
(out / "chess.rtf").write_text(rtf)
(out / "README.txt").write_text("Generated by tools/generate-document-fixtures.py. Synthetic FEN/PGN, with the existing board-recognition test image. No user data. Word, Excel, PowerPoint and PDF files are generated with independent authoring libraries. locked.pdf password: fixture-password.\n")
print("Created:", ", ".join(p.name for p in out.iterdir()))
